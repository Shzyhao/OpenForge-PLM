-- 通知订阅模型（v1.24 设计 §4）：发布类事件（part/bom/doc/drawing）payload 无收件人语义，
-- 改由用户显式订阅——同租户 + event_key fan-out（上限沿用 ROLE 通道的 50 截断）。
-- 审批流事件（task.created/completed）收件人明确，不走订阅。

CREATE TABLE notify_subscription (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL DEFAULT 0,
    user_id    BIGINT      NOT NULL,
    event_key  VARCHAR(64) NOT NULL,   -- part.released/bom.published/doc.released/drawing.released/drawing.obsolete
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_notify_sub UNIQUE (user_id, event_key)
);
CREATE INDEX idx_notify_sub_tenant ON notify_subscription (tenant_id, event_key);
